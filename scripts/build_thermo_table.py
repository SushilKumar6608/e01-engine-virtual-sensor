"""Build the frozen NASA-7 thermo table used by the simulators.

SIMULATION PROJECT - no real engine data is used anywhere in this repo.

Why a frozen table instead of calling Cantera at run time?
  * The simulators need only h(T) and cp(T) of five product/air species and the
    formation enthalpy of the two fuels. Those are polynomials (NASA-7).
  * Evaluating the polynomials with NumPy is vectorised and fast enough to
    generate hundreds of thousands of 1 Hz samples.
  * The ONNX/inference path then does not need Cantera installed.
  * Cantera remains the *reference*: tests compare the NumPy evaluation against
    Cantera's own h(T), cp(T) at many temperatures.

Species data come from Cantera's shipped files:
  gri30.yaml           -> CO2, H2O, N2, O2, AR, CH3OH (methanol)
  nDodecane_Reitz.yaml -> c12h26 (n-dodecane, the diesel-like surrogate)
Only thermodynamic data are taken. No reaction kinetics are used.
"""
from __future__ import annotations

import json
from pathlib import Path

import cantera as ct
import numpy as np

OUT = Path(__file__).resolve().parents[1] / "src" / "vsensor" / "sim" / "thermo_nasa7.json"

# table name -> (Cantera file, species name inside that file)
SPECIES = {
    "CO2": ("gri30.yaml", "CO2"),
    "H2O": ("gri30.yaml", "H2O"),
    "N2": ("gri30.yaml", "N2"),
    "O2": ("gri30.yaml", "O2"),
    "AR": ("gri30.yaml", "AR"),
    "CH3OH": ("gri30.yaml", "CH3OH"),
    "C12H26": ("nDodecane_Reitz.yaml", "c12h26"),  # lower-case in the Reitz file
}


def nasa7_h(c_low, c_high, t_mid, T):
    """Molar enthalpy [J/kmol] from NASA-7 coefficients (same maths as sim/thermo.py)."""
    # Cantera evaluates the low-temperature polynomial up to and including T_mid.
    a = np.asarray(c_high if T > t_mid else c_low)
    h_rt = a[0] + a[1] * T / 2 + a[2] * T**2 / 3 + a[3] * T**3 / 4 + a[4] * T**4 / 5 + a[5] / T
    return h_rt * ct.gas_constant * T


def main() -> None:
    phases = {f: ct.Solution(f) for f, _ in set(SPECIES.values())}
    table = {}
    for name, (fname, ct_name) in SPECIES.items():
        sp = phases[fname].species(ct_name)
        th = sp.thermo
        coeffs = np.asarray(th.coeffs, dtype=float)
        assert coeffs.shape == (15,), f"{name}: unexpected NASA-7 layout {coeffs.shape}"
        t_mid = float(coeffs[0])
        c_high = coeffs[1:8].tolist()
        c_low = coeffs[8:15].tolist()
        # Self-check the assumed layout [T_mid, high(7), low(7)] against Cantera itself.
        for T in np.linspace(max(th.min_temp, 250.0), min(th.max_temp, 2500.0), 25):
            ref = th.h(T)
            mine = nasa7_h(c_low, c_high, t_mid, T)
            assert abs(mine - ref) <= 1e-9 * max(1.0, abs(ref)), (name, T, mine, ref)
        table[name] = {
            "source_file": fname,
            "cantera_name": ct_name,
            "molecular_weight_kg_per_kmol": float(sp.molecular_weight),
            "composition": {k: float(v) for k, v in sp.composition.items()},
            "t_min": float(th.min_temp),
            "t_mid": t_mid,
            "t_max": float(th.max_temp),
            "coeffs_low": c_low,
            "coeffs_high": c_high,
        }
    payload = {
        "_note": "SIMULATION PROJECT. NASA-7 thermo data extracted from Cantera; generated by scripts/build_thermo_table.py. Do not edit by hand.",
        "cantera_version": ct.__version__,
        "gas_constant_J_per_kmol_K": float(ct.gas_constant),
        "species": table,
    }
    OUT.write_text(json.dumps(payload, indent=1) + "\n")
    print(f"wrote {OUT} ({len(table)} species, Cantera {ct.__version__})")


if __name__ == "__main__":
    main()

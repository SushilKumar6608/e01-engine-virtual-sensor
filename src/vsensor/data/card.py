"""Data card and data quality report writers (SIMULATED DATA)."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from vsensor.data.config import DatasetConfig
from vsensor.data.generate import MODEL_INPUT_COLUMNS, ROOT, TARGET_COLUMN, load_manifest, load_split
from vsensor.params import Registry

LABEL = "SIMULATED DATA - generated by a simplified mean-value engine model, not measured on any engine"


def write_card(cfg: DatasetConfig, reg: Registry, data_dir: Path, path: Path | None = None) -> Path:
    path = path or ROOT / "docs" / "DATA_CARD.md"
    man = load_manifest(data_dir)
    meta = pd.read_parquet(data_dir / "episodes.parquet")
    counts = reg.status_counts()
    rows = []
    for name, s in cfg.splits.items():
        m = man["splits"][name]
        rows.append(f"| {name} | {s.episodes} | {m['rows']} | {', '.join(f'{k} {v:.0%}' for k, v in s.fuel_mix.items())} | "
                    f"{', '.join(f'{k} {b[0]:.2f}-{b[1]:.2f}' for k, b in s.load_band.items())} | {s.purpose} |")
    t = f"""# Data card: {cfg.name}

**{LABEL}.** Nothing here has been validated against a real engine. Results obtained on these data rest on the simulator.

## Purpose

Training and honest testing of an uncertainty-aware virtual sensor for the exhaust gas temperature before the turbine of a large two-stroke marine-style engine, with a diesel-like fuel (n-dodecane surrogate) and methanol. The data also serve to test how the sensor behaves in regimes it did not see (high load, methanol at low load, cold ambient), with injected sensor faults, and when asked to abstain (30-35 % load). The study range is 40-100 % load.

## Contents

Sampling 1 Hz, episodes of {cfg.episode_duration_s} s. For every split two tables: `signals_<split>.parquet` (what a model may see) and `truth_<split>.parquet` (hidden plant states and noise-free values; for evaluation and gate checks only, never as a model input).

Model-visible columns: `{', '.join(MODEL_INPUT_COLUMNS)}`; target `{TARGET_COLUMN}` (the measured, noisy, lagged exhaust sensor value). Units: speed rpm, fuel flow kg/s, pressures bar, temperatures K, turbocharger speed rpm. `fuel_code` 0 = diesel-like, 1 = methanol. Missing values (NaN) occur only at injected sensor dropouts. `episodes.parquet` lists per-episode sensor biases, drift rates, fault type and a content digest; `events.parquet` lists dropouts and injected faults.

## How the data were generated

A quasi-steady plant solution (energy balance, speed-density air flow, turbine and compressor power balance, air cooler) is solved every second for a smooth load profile, followed by first-order lags for the slow signals, then a sensor model (lag, bias, drift, noise, quantisation, dropouts). Hidden fouling states of the turbocharger and the air cooler vary per episode. Every episode has its own seeded random generator, so any episode can be rebuilt from the configuration and its seed alone. Base seed {cfg.base_seed}.

Registry: {len(reg.ids)} parameters: {', '.join(f'{counts.get(k, 0)} {k}' for k in ('sourced', 'derived', 'calibrated', 'assumed'))}. **All sensor noise levels, lag constants, health distributions and profile settings are assumed**, with a written rationale in `docs/PARAMETERS.md`. Methanol shares the diesel efficiency curve in the main data (assumption).

## Splits

| split | episodes | rows | fuel mix | load band | purpose |
|---|---|---|---|---|---|
{chr(10).join(rows)}

Episodes are never shared between splits; each split has its own seed id. The regime splits are held out by construction: training load is at most 0.90, methanol training load at least 0.55, training ambient temperatures above those of the cold split. Calibration and validation data are separate from training data.

## Known limits

* The simulator is a simplified steady-state-plus-lag model with generic parameters. The stroke, the air delivery law, the load dependence of exhaust temperature and the sizes of fouling and ambient effects are assumptions or unverified (see `docs/MODEL_CHOICES.md`, open items).
* Exhaust temperature may exceed 800 K at heavy fouling; no source covers that region.
* Sensor noise and lag values are plausible guesses, not instrument data sheets.
* Cold ambient is not a hard regime shift for the nominal model (earlier finding).
* 30-35 % load data (`stress_low_load`) are used only for the abstention stress test; no accuracy or coverage is reported there.
* Methanol efficiency stress splits (-3 % / +3 %) test sensitivity to the shared-curve assumption; they come from the plant only.
* Wording rule: results "rest on the simulator", never "on verified physics".

## Provenance

* Dataset hash (sha256): `{man['dataset_hash']}`
* Configuration hash: `{man['config_hash']}`
* Registry hash (without the nominal-model parameters): `{man['registry_hash']}`
* Generator code hash: `{man['generator_code_hash']}`
* Schema version {cfg.schema_version}; {int(meta.shape[0])} episodes.
* Rebuild: `python scripts/build_dataset.py --full-check` must give the same dataset hash. The hash was computed on the generating platform; a different platform may produce a different hash if floating-point results differ in the last digits (measured values are hashed after rounding to 1e-6).
"""
    path.write_text(t)
    return path


def write_quality_report(gates, cfg: DatasetConfig, data_dir: Path, out_dir: Path | None = None) -> Path:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir = out_dir or ROOT / "reports" / "data"
    out_dir.mkdir(parents=True, exist_ok=True)
    man = load_manifest(data_dir)
    sig = load_split(data_dir, "train")
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    for code, c, lab in ((0, "#2a6fb0", "diesel-like"), (1, "#e08a1e", "methanol")):
        s = sig[sig["fuel_code"] == code]
        ax[0].scatter(s["n_rpm"][::40], s["m_fuel"][::40], s=3, color=c, label=lab)
    ax[0].set_xlabel("speed [rpm]"); ax[0].set_ylabel("fuel flow [kg/s]"); ax[0].set_title("Training coverage (every 40th row)"); ax[0].legend()
    eid = sig["episode_id"].iloc[0]
    e = sig[sig["episode_id"] == eid]
    ax[1].plot(e["t_s"], e[TARGET_COLUMN], color="#2a6fb0", lw=1)
    ax[1].set_xlabel("time [s]"); ax[1].set_ylabel("measured exhaust temperature [K]"); ax[1].set_title(f"Example episode {eid}")
    fig.suptitle("SIMULATED DATA", color="gray")
    fig.tight_layout(); fig.savefig(out_dir / "fig_coverage_and_example.png", dpi=110); plt.close(fig)
    lines = ["# Data quality report", "", f"**{LABEL}.** Dataset `{cfg.name}`, hash `{man['dataset_hash']}`.", "",
             "| Gate | Result |", "|---|---|"]
    lines += [f"| {g.number}. {g.name} | {g.summary if len(g.summary) < 90 else g.summary[:90] + '...'} |" for g in gates]
    lines += ["", "![Coverage and example](fig_coverage_and_example.png)", ""]
    for g in gates:
        lines += [f"## Gate {g.number}: {g.name} - {'PASS' if g.passed else 'FAIL'}", ""] + [f"* {d}" for d in g.details] + [""]
    lines += ["Gate 9 needs one manual step: a person must read `docs/DATA_CARD.md` before release.", ""]
    p = out_dir / "data_quality_report.md"
    p.write_text("\n".join(lines))
    return p
